-- 1. CLIENTE
CREATE TABLE IF NOT EXISTS public.cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    telefono VARCHAR(20),
    direccion VARCHAR(100),
    correo VARCHAR(100)
);

-- 2. REPARTIDOR
CREATE TABLE IF NOT EXISTS public.repartidor (
    id_repartidor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    apellido VARCHAR(50) NOT NULL,
    telefono VARCHAR(20),
    estado VARCHAR(20) NOT NULL DEFAULT 'Disponible'
);

-- 3. PRODUCTO
CREATE TABLE IF NOT EXISTS public.producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(100),
    precio NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    disponible BOOLEAN NOT NULL DEFAULT TRUE
);

-- 4. DATO DEMANDA
CREATE TABLE IF NOT EXISTS public.dato_demanda (
    id_dato_demanda INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP NOT NULL,
    cantidad_pedidos INTEGER NOT NULL DEFAULT 0,
    ventas_totales NUMERIC(10,2) NOT NULL DEFAULT 0,
    promocion_activa BOOLEAN NOT NULL DEFAULT FALSE,
    temperatura NUMERIC(5,2),
    precipitacion NUMERIC(5,2)
);

-- 5. EJECUCION PREDICCION
CREATE TABLE IF NOT EXISTS public.ejecucion_prediccion (
    id_ejecucion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_generacion TIMESTAMP NOT NULL DEFAULT NOW(),
    algoritmo VARCHAR(50) NOT NULL
);

-- 6. PEDIDO
CREATE TABLE IF NOT EXISTS public.pedido (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL REFERENCES public.cliente(id_cliente),
    id_repartidor INTEGER REFERENCES public.repartidor(id_repartidor),
    id_dato_demanda INTEGER REFERENCES public.dato_demanda(id_dato_demanda),
    fecha_hora TIMESTAMP NOT NULL DEFAULT NOW(),
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    total NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    fecha_hora_entrega TIMESTAMP
);

-- 7. DETALLE PEDIDO
CREATE TABLE IF NOT EXISTS public.detalle_pedido (
    id_pedido INTEGER NOT NULL REFERENCES public.pedido(id_pedido) ON DELETE CASCADE,
    id_producto INTEGER NOT NULL REFERENCES public.producto(id_producto),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),
    PRIMARY KEY (id_pedido, id_producto)
);

-- 8. DETALLE EJECUCION
CREATE TABLE IF NOT EXISTS public.detalle_ejecucion (
    id_ejecucion INTEGER NOT NULL REFERENCES public.ejecucion_prediccion(id_ejecucion) ON DELETE CASCADE,
    id_dato_demanda INTEGER NOT NULL REFERENCES public.dato_demanda(id_dato_demanda),
    cantidad_muestra INTEGER NOT NULL DEFAULT 1 CHECK (cantidad_muestra > 0),
    PRIMARY KEY (id_ejecucion, id_dato_demanda)
);

-- 9. PREDICCION DEMANDA
CREATE TABLE IF NOT EXISTS public.prediccion_demanda (
    id_prediccion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejecucion INTEGER NOT NULL REFERENCES public.ejecucion_prediccion(id_ejecucion) ON DELETE CASCADE,
    periodo_predicho TIMESTAMP NOT NULL,
    cantidad_estimada NUMERIC(10,2) NOT NULL
);

-- =====================================================
-- INDICES PARA CLAVES FORANEAS Y CONSULTAS
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_pedido_cliente
    ON public.pedido(id_cliente);

CREATE INDEX IF NOT EXISTS idx_pedido_repartidor
    ON public.pedido(id_repartidor);

CREATE INDEX IF NOT EXISTS idx_pedido_demanda
    ON public.pedido(id_dato_demanda);

CREATE INDEX IF NOT EXISTS idx_pedido_fecha
    ON public.pedido(fecha_hora);

CREATE INDEX IF NOT EXISTS idx_detalle_producto
    ON public.detalle_pedido(id_producto);

CREATE INDEX IF NOT EXISTS idx_detalle_ejecucion_demanda
    ON public.detalle_ejecucion(id_dato_demanda);

CREATE INDEX IF NOT EXISTS idx_prediccion_ejecucion
    ON public.prediccion_demanda(id_ejecucion);

-- =====================================================
-- SEGURIDAD RLS
-- MVP ACADEMICO: acceso compartido sin autenticacion real
-- =====================================================

DO $$
DECLARE
    tabla TEXT;
BEGIN
    FOREACH tabla IN ARRAY ARRAY[
        'cliente',
        'repartidor',
        'producto',
        'dato_demanda',
        'pedido',
        'detalle_pedido',
        'ejecucion_prediccion',
        'detalle_ejecucion',
        'prediccion_demanda'
    ]
    LOOP
        EXECUTE format(
            'ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',
            tabla
        );

        EXECUTE format(
            'GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO anon, authenticated',
            tabla
        );

        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)',
            'acceso_mvp_' || tabla,
            tabla
        );
    END LOOP;
END $$;

-- Permisos para las secuencias IDENTITY
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public
TO anon, authenticated;
